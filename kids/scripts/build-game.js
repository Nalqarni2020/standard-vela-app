/* Packs game/little-astronaut.html into src/game.ts as one HTML document string.
   Run after editing the game:  node scripts/build-game.js */
const fs = require("fs"), path = require("path");
const body = fs.readFileSync(path.join(__dirname, "../game/little-astronaut.html"), "utf8");
const doc = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover"></head><body>' + body + "</body></html>";
fs.writeFileSync(path.join(__dirname, "../src/game.ts"), "/* Generated by scripts/build-game.js from game/little-astronaut.html. Do not edit by hand. */\nexport const GAME_HTML = " + JSON.stringify(doc) + ";\n");
console.log("src/game.ts written,", doc.length, "characters");
